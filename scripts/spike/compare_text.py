"""M0.2: compare page text from PDFKit, PDFium and poppler on the smoke set.

Run from the repo root, after building `pdf`:

    uv run --with pypdfium2 python scripts/spike/compare_text.py

Writes spike/M0.2-text.md (metrics and side-by-side excerpts) and the raw
page text of each engine to spike/out/.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
import time
from difflib import SequenceMatcher
from pathlib import Path

import pypdfium2 as pdfium

ROOT = Path(__file__).resolve().parents[2]
SMOKE = ROOT / "testdata" / "smoke"
OUT = ROOT / "spike" / "out"
REPORT = ROOT / "spike" / "M0.2-text.md"
PDF_BIN = ROOT / ".build" / "release" / "pdf"

LIGATURES = set("ﬀﬁﬂﬃﬄﬅﬆ")
WORD = re.compile(r"[A-Za-z]+")
BROKEN_HYPHEN = re.compile(r"[a-z]-\n[a-z]")


def pdfkit_pages(path: Path) -> tuple[list[str], float]:
    start = time.perf_counter()
    out = subprocess.run([str(PDF_BIN), "spike", "text", str(path)], capture_output=True, text=True, check=True)
    elapsed = time.perf_counter() - start
    # Split on "\n" only: str.splitlines() also splits on U+2028, which JSON strings may contain.
    pages = [json.loads(line)["text"] for line in out.stdout.split("\n") if line.strip()]
    return pages, elapsed


def pdfium_pages(path: Path) -> tuple[list[str], float]:
    start = time.perf_counter()
    document = pdfium.PdfDocument(str(path))
    pages = []
    for index in range(len(document)):
        textpage = document[index].get_textpage()
        pages.append(textpage.get_text_range())
    return pages, time.perf_counter() - start


def poppler_pages(path: Path) -> tuple[list[str], float]:
    start = time.perf_counter()
    out = subprocess.run(["pdftotext", "-enc", "UTF-8", str(path), "-"], capture_output=True, text=True, check=True)
    pages = out.stdout.split("\f")
    if pages and not pages[-1].strip():
        pages = pages[:-1]
    return pages, time.perf_counter() - start


def metrics(pages: list[str]) -> dict[str, float]:
    # PDFium ends lines with \r\n, and marks a hyphen at a line break as U+FFFE.
    text = "\n".join(pages).replace("\r\n", "\n").replace("\r", "\n")
    words = WORD.findall(text)
    glued = sum(1 for word in words if len(word) > 25)
    return {
        "chars": len(text),
        "garbled": text.count("�") + text.count("(cid:") + sum(1 for ch in text if 0xE000 <= ord(ch) <= 0xF8FF),
        "ligatures": sum(1 for ch in text if ch in LIGATURES),
        "glued_per_1k_words": 1000 * glued / max(len(words), 1),
        "line_end_hyphens": len(BROKEN_HYPHEN.findall(text)),
        "marked_hyphens": text.count("￾"),
    }


def agreement(a: list[str], b: list[str]) -> float:
    """Word-level similarity between two engines, averaged over pages."""
    scores = []
    for left, right in zip(a, b):
        lw, rw = WORD.findall(left), WORD.findall(right)
        if not lw and not rw:
            continue
        scores.append(SequenceMatcher(None, lw, rw, autojunk=False).ratio())
    return sum(scores) / len(scores) if scores else 0.0


def excerpt(text: str, limit: int = 700) -> str:
    return text.strip()[:limit].replace("```", "'''")


def main() -> int:
    pdfs = sorted(SMOKE.glob("*.pdf"))
    if not pdfs:
        print(f"no PDFs in {SMOKE}", file=sys.stderr)
        return 1
    OUT.mkdir(parents=True, exist_ok=True)

    rows = []
    excerpts = []
    totals = {"pdfkit": [0.0, 0], "pdfium": [0.0, 0], "poppler": [0.0, 0]}
    for path in pdfs:
        engines = {
            "pdfkit": pdfkit_pages(path),
            "pdfium": pdfium_pages(path),
            "poppler": poppler_pages(path),
        }
        for name, (pages, elapsed) in engines.items():
            (OUT / f"{path.stem}.{name}.txt").write_text("\n\f\n".join(pages))
            totals[name][0] += elapsed
            totals[name][1] += len(pages)
            m = metrics(pages)
            rows.append((path.name, name, len(pages), m, 1000 * elapsed / max(len(pages), 1)))
        kit, ium, pop = (engines[n][0] for n in ("pdfkit", "pdfium", "poppler"))
        rows.append((path.name, "agreement", 0, {
            "pdfkit~pdfium": agreement(kit, ium),
            "pdfkit~poppler": agreement(kit, pop),
            "pdfium~poppler": agreement(ium, pop),
        }, 0))
        page = 1 if len(kit) > 1 else 0
        excerpts.append((path.name, page + 1, {n: excerpt(engines[n][0][page]) for n in engines if len(engines[n][0]) > page}))

    lines = ["# M0.2 — Text from PDFKit, PDFium and poppler", ""]
    lines.append("Generated by `scripts/spike/compare_text.py` on the smoke set in `testdata/smoke/`.")
    lines.append("")
    lines.append("## Speed")
    lines.append("")
    lines.append("| Engine | Pages | Total s | ms per page |")
    lines.append("|---|---|---|---|")
    for name, (seconds, count) in totals.items():
        lines.append(f"| {name} | {count} | {seconds:.2f} | {1000 * seconds / max(count, 1):.1f} |")
    lines.append("")
    lines.append("PDFKit times include starting the `pdf` process once per file.")
    lines.append("")
    lines.append("## Text quality per file")
    lines.append("")
    lines.append("| File | Engine | Pages | Chars | Garbled | Ligatures | Glued words per 1k | Line-end hyphens kept | Line-end hyphens marked |")
    lines.append("|---|---|---|---|---|---|---|---|---|")
    for name, engine, pages, m, _ in rows:
        if engine == "agreement":
            continue
        lines.append(f"| {name} | {engine} | {pages} | {m['chars']} | {m['garbled']} | {m['ligatures']} | {m['glued_per_1k_words']:.2f} | {m['line_end_hyphens']} | {m['marked_hyphens']} |")
    lines.append("")
    lines.append("## Agreement between engines (word-level similarity, 1.0 = identical)")
    lines.append("")
    lines.append("| File | PDFKit ~ PDFium | PDFKit ~ poppler | PDFium ~ poppler |")
    lines.append("|---|---|---|---|")
    for name, engine, _, m, _ in rows:
        if engine == "agreement":
            lines.append(f"| {name} | {m['pdfkit~pdfium']:.3f} | {m['pdfkit~poppler']:.3f} | {m['pdfium~poppler']:.3f} |")
    lines.append("")
    lines.append("## Side by side: the start of page 2")
    lines.append("")
    for name, page, texts in excerpts:
        lines.append(f"### {name}, page {page}")
        lines.append("")
        for engine, text in texts.items():
            lines.append(f"**{engine}**")
            lines.append("")
            lines.append("```text")
            lines.append(text)
            lines.append("```")
            lines.append("")
    REPORT.write_text("\n".join(lines))
    print(f"wrote {REPORT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
